#!/usr/bin/env node
// Generate Tinycast/Features/Dictation/Model/DictationModelFiles.generated.swift.
//
// Usage: node Scripts/gen-dictation-manifest.js
// Run after changing a model's repository, revision or components in DictationModel.swift, and
// commit the output. `dictation-test` fails while the two disagree.
//
// The app downloads models from Hugging Face. Asking the host at install time which files exist
// and what they hash to would let a compromised host serve anything, so the answer is fixed here.
// Large files carry their SHA-256 in the tree listing; small ones are fetched and hashed.
"use strict";

const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const HOST = "https://huggingface.co";
const QWEN_TOKENIZER = {
  repository: "Qwen/Qwen3-ASR-0.6B",
  revision: "5eb144179a02acc5e5ba31e748d22b0cf3e303b0",
  components: ["vocab.json", "merges.txt"],
};
const QWEN = ["encoder.mlmodelc", "decoder.mlmodelc", "embedding.mlmodelc", "config.json"];
const PARAKEET = ["Preprocessor.mlmodelc", "Encoder.mlmodelc", "Decoder.mlmodelc", "JointDecisionv3.mlmodelc", "parakeet_vocab.json"];

// Mirrors DictationModel's repository, revision and components; the harness checks they match.
const MODELS = {
  redux: [{ repository: "FluidInference/parakeet-redux-coreml", revision: "8c5ef97a29cd120dc76b354b3f22b7fec3b486f9", components: PARAKEET }],
  ultra: [{ repository: "FluidInference/parakeet-ultra-coreml", revision: "95eaa59a39d4394f047a4dc5cce480388a60d1b6", components: PARAKEET }],
  qwenSmall: [{ repository: "UniMocha/Qwen3-ASR-0.6B-CoreML-INT8", revision: "27b7a26835d7c2cd1cf774b4c490eb5519ca71a0", components: QWEN }, QWEN_TOKENIZER],
  qwenLarge: [{ repository: "UniMocha/Qwen3-ASR-1.7B-CoreML-INT8", revision: "06312fbac1383cd22e1000c28b017634e03251a2", components: QWEN }, QWEN_TOKENIZER],
};

async function json(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.json();
}

async function sha256(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return crypto.createHash("sha256").update(Buffer.from(await response.arrayBuffer())).digest("hex");
}

async function files({ repository, revision, components }) {
  const tree = await json(`${HOST}/api/models/${repository}/tree/${revision}?recursive=true`);
  const wanted = tree.filter((file) => file.type === "file" && components.includes(file.path.split("/")[0]));
  for (const component of components) {
    if (!wanted.some((file) => file.path === component || file.path.startsWith(component + "/"))) {
      throw new Error(`${repository}@${revision} has no ${component}`);
    }
  }
  const out = [];
  for (const file of wanted.sort((a, b) => a.path.localeCompare(b.path))) {
    const hash = file.lfs ? file.lfs.oid : await sha256(`${HOST}/${repository}/resolve/${revision}/${file.path}`);
    out.push({ repository, revision, path: file.path, size: file.size, sha256: hash });
  }
  return out;
}

const quote = (text) => JSON.stringify(text);

async function main() {
  const lines = [
    "// Generated by `node Scripts/gen-dictation-manifest.js`. Never edit by hand.",
    "",
    "extension DictationModelFiles {",
    "    static let pinned: [DictationModel: [File]] = [",
  ];
  for (const [model, sources] of Object.entries(MODELS)) {
    lines.push(`        .${model}: [`);
    for (const source of sources) {
      for (const file of await files(source)) {
        lines.push(
          `            File(repository: ${quote(file.repository)}, revision: ${quote(file.revision)},`,
          `                 path: ${quote(file.path)}, size: ${file.size},`,
          `                 sha256: ${quote(file.sha256)}),`,
        );
      }
    }
    lines.push("        ],");
  }
  lines.push("    ]", "}", "");
  const target = path.join(__dirname, "..", "Tinycast/Features/Dictation/Model/DictationModelFiles.generated.swift");
  fs.writeFileSync(target, lines.join("\n"));
  console.log(`Wrote ${target}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
